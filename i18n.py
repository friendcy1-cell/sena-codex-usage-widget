def tr(language, key, **values):
    return CATALOGS.get(language, EN).get(key, EN[key]).format(**values)


def quota_name(window, language):
    minutes = window.get("minutes")
    if minutes in (300, 10080):
        return tr(language, "five_hour" if minutes == 300 else "weekly")
    return tr(language, "hours", n=f"{minutes / 60:g}") if minutes else tr(language, "usage")
